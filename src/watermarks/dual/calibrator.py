def infer_model_key(model_path: str) -> str:
    model_path = (model_path or "").lower()
    if "llama3" in model_path or "llama-3" in model_path:
        return "llama3.1-8b"
    return "llama3.1-8b"


def get_calibration_params(tokenizer, text: str, dataset_type: str, model_key: str, macro_name: str):
    tokens = tokenizer.encode(text, add_special_tokens=False)
    actual_len = len(tokens)
    dataset_type = (dataset_type or "c4").lower()

    ds_params = CALIB_PARAMS.get(dataset_type, CALIB_PARAMS.get("c4", {}))
    model_params = ds_params.get(model_key, ds_params.get("llama3.1-8b", {}))

    available_lens = list(model_params.keys())
    if not available_lens:
        return 0.0, 1.0

    closest_len = min(available_lens, key=lambda x: abs(x - actual_len))
    method_params = model_params[closest_len].get(macro_name, None)

    if method_params is None:
        return 0.0, 1.0

    return method_params["mu"], method_params["sigma"]