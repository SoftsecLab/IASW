def find_record_for_method(unit_dir: Path, method_key: str) -> Optional[Path]:
    """
    Find the canonical JSONL for one method inside one ablation unit.
    """
    if FLAT_RECORDS:
        exact = unit_dir / f"{method_key}.jsonl"
        if exact.exists():
            return exact
        records = discover_record_files(unit_dir)
        if method_key in records:
            return records[method_key]
        return None

    for records_dir in sorted(unit_dir.rglob("records")):
        if not records_dir.is_dir():
            continue

        exact = records_dir / f"{method_key}.jsonl"
        if exact.exists():
            return exact

        records = discover_record_files(records_dir)
        if method_key in records:
            return records[method_key]

    return None


def extract_channel_scores_for_record(
    path: Path,
    channel: str,
    negative_source: str = "human",
) -> Tuple[List[float], List[float], Dict[str, List[float]]]:
    """
    Extract one statistic from a dual JSONL.

    channel:
        word      -> micro / token-level statistic
        semantic  -> calibrated macro / IAS-W statistic
        max       -> Max fusion
        fisher    -> Fisher fusion
    """
    negatives = []
    wm = []
    attacks = {a: [] for a in ATTACKS}

    def select(res: dict) -> float:
        p = parse_detection_result(res)
        if not p:
            return np.nan

        if channel == "word":
            return p["micro"]

        if channel == "semantic":
            return p["macro"]

        if channel == "max":
            if np.isfinite(p["max"]):
                return p["max"]
            if np.isfinite(p["micro"]) and np.isfinite(p["macro"]):
                return max(p["micro"], p["macro"])
            return np.nan

        if channel == "fisher":
            if np.isfinite(p["fisher"]):
                return p["fisher"]
            return fisher_fusion(p["micro"], p["macro"])

        raise ValueError(f"Unknown channel: {channel}")

    for row in load_jsonl(path):
        if negative_source == "human":
            neg_res = row.get("detection_human") or row.get("detection_no_wm") or {}
        else:
            neg_res = row.get("detection_no_wm") or row.get("detection_human") or {}

        neg = select(neg_res)
        pos = select(row.get("detection_wm") or {})

        if np.isfinite(neg):
            negatives.append(float(neg))
        if np.isfinite(pos):
            wm.append(float(pos))

        atk_pack = row.get("attacks") or {}
        for attack in ATTACKS:
            data = atk_pack.get(attack)
            if not isinstance(data, dict):
                continue

            score = select(data.get("detection_results") or {})
            if np.isfinite(score):
                attacks[attack].append(float(score))

    return negatives, wm, attacks


def average_attack_metric(
    negatives: List[float],
    attacks: Dict[str, List[float]],
    metric: str,
) -> float:
    vals = []
    for attack in ATTACKS:
        pos = attacks.get(attack, [])
        if not pos:
            continue
        value = detection_metrics(negatives, pos).get(metric, np.nan)
        if np.isfinite(value):
            vals.append(float(value))
    return float(np.mean(vals)) if vals else np.nan


def average_attack_tpr1(
    negatives: List[float],
    attacks: Dict[str, List[float]],
) -> float:
    """Backward-compatible alias for older callers."""
    return average_attack_metric(negatives, attacks, "TPR@1%FPR")

def collect_candidate_ablation() -> pd.DataFrame:
    """
    Candidate-number source table with average attacked AUROC, TPR@1%FPR,
    and TPR@5%FPR for every plotted series.
    """
    root = ABLATION_ROOT / "num_candidates"
    rows = []

    for value in CANDIDATE_VALUES:
        unit = root / f"cand{value}"
        if not unit.exists():
            continue

        for method_key, label in CANDIDATE_SERIES:
            path = find_record_for_method(unit, method_key)
            if path is None:
                print(f"[WARN] candidate ablation missing: K={value}, method={method_key}")
                continue

            neg, _, atk = extract_detection_scores(
                path,
                method_key=method_key,
                negative_source="human",
            )

            rows.append({
                "value": value,
                "series_key": method_key,
                "Method": label,
                "Avg_Attacked_AUC": average_attack_metric(neg, atk, "AUC"),
                "Avg_Attacked_TPR@1%FPR": average_attack_metric(neg, atk, "TPR@1%FPR"),
                "Avg_Attacked_TPR@5%FPR": average_attack_metric(neg, atk, "TPR@5%FPR"),
                "record_file": str(path.relative_to(PROJECT_ROOT)),
            })

    return pd.DataFrame(rows)

def collect_token_length_ablation() -> pd.DataFrame:
    """
    Target-length source table with average attacked AUROC, TPR@1%FPR,
    and TPR@5%FPR for each detector statistic.
    """
    root = ABLATION_ROOT / "token_length"
    rows = []

    def append_row(value, series_key, label, path, neg, atk):
        rows.append({
            "value": value,
            "series_key": series_key,
            "Method": label,
            "Avg_Attacked_AUC": average_attack_metric(neg, atk, "AUC"),
            "Avg_Attacked_TPR@1%FPR": average_attack_metric(neg, atk, "TPR@1%FPR"),
            "Avg_Attacked_TPR@5%FPR": average_attack_metric(neg, atk, "TPR@5%FPR"),
            "record_file": str(path.relative_to(PROJECT_ROOT)),
        })

    for value in TOKEN_LENGTH_VALUES:
        unit = root / f"len{value}"
        if not unit.exists():
            continue

        kgw_path = find_record_for_method(unit, "kgw")
        if kgw_path is not None:
            neg, _, atk = extract_detection_scores(
                kgw_path,
                method_key="kgw",
                negative_source="human",
            )
            append_row(value, "kgw", "KGW Only", kgw_path, neg, atk)
        else:
            print(f"[WARN] token-length ablation missing KGW: len={value}")

        dual_path = find_record_for_method(unit, "dual_kgw_iasw")
        if dual_path is None:
            print(f"[WARN] token-length ablation missing dual_kgw_iasw: len={value}")
            continue

        for channel, label in [
            ("word", "Token-Level Statistic (KGW+IAS-W)"),
            ("semantic", "IAS-W Alignment Statistic (KGW+IAS-W)"),
            ("fisher", "KGW+IAS-W (Fisher Fusion)"),
        ]:
            neg, _, atk = extract_channel_scores_for_record(
                dual_path,
                channel=channel,
                negative_source="human",
            )
            append_row(
                value,
                f"dual_kgw_iasw:{channel}",
                label,
                dual_path,
                neg,
                atk,
            )

    return pd.DataFrame(rows)

