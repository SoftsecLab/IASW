def normalize_stage_name(s: str) -> str:
    """Normalize metric-stage names such as 'After Back_translation'."""
    if not isinstance(s, str):
        return ""
    return "_".join(s.strip().lower().replace("-", "_").split())


def get_stage_metrics(channel_dict: dict, stage_name: str):
    """Case/underscore-tolerant stage lookup, matching auto_summarize.py."""
    if not isinstance(channel_dict, dict):
        return None

    if stage_name in channel_dict:
        return channel_dict[stage_name]

    target = normalize_stage_name(stage_name)
    for real_name, metrics in channel_dict.items():
        if normalize_stage_name(real_name) == target:
            return metrics
    return None


def is_ablation_metrics_file(path: Path) -> bool:
    return path.name.lower().endswith("_ablation_metrics.json")


def collect_metrics_files_for_method(
    plots_dir: Path,
    method_key: str,
) -> List[Tuple[Path, dict]]:
    """
    Find official non-ablation *_metrics.json files whose embedded
    ``method`` field exactly matches ``method_key``.

    We match by JSON content rather than filename because native baselines may
    use different plot filenames while still reporting the canonical method.
    """
    matches: List[Tuple[Path, dict]] = []
    if not plots_dir.exists():
        return matches

    for path in sorted(plots_dir.glob("*_metrics.json")):
        if is_ablation_metrics_file(path):
            continue
        try:
            with path.open("r", encoding="utf-8") as f:
                data = json.load(f)
        except Exception as e:
            print(f"[WARN] cannot read metrics file {path}: {e}")
            continue

        method = str(data.get("method", "")).strip().lower()
        if method == method_key.lower():
            matches.append((path, data))

    return matches


def summarize_metrics_method(
    plots_dir: Path,
    method_key: str,
) -> Optional[Dict[str, float]]:
    """
    Build one build_paper robustness row directly from official plot metrics.

    For single native baselines (DualMark/SynGuard), use the active
    channel exactly as auto_summarize.py does: prefer Micro when it contains
    Before Attack, otherwise use Macro.  If several metric files exist for the
    same method (e.g. one per attack), their stages are merged.
    """
    files = collect_metrics_files_for_method(plots_dir, method_key)
    if not files:
        return None

    target_metrics = ["AUC", "TPR@0.1%FPR", "TPR@1%FPR", "TPR@5%FPR"]
    item: Dict[str, float] = {
        "method_key": method_key,
        "Method": display_method(method_key),
        "record_file": " | ".join(
            str(path.relative_to(PROJECT_ROOT)) for path, _ in files
        ),
        "negative_n": np.nan,
        "wm_n": np.nan,
    }

    # Initialize all expected paper fields, so partial metric files remain safe.
    for metric in target_metrics:
        item[f"Unattacked_{metric}"] = np.nan
    for attack in ATTACKS:
        item[f"{attack}_n"] = np.nan
        for metric in target_metrics:
            item[f"{attack}_{metric}"] = np.nan

    for path, data in files:
        micro = data.get("Micro")
        macro = data.get("Macro")

        if isinstance(micro, dict) and get_stage_metrics(micro, "Before Attack") is not None:
            channel = micro
            channel_name = "Micro"
        elif isinstance(macro, dict) and get_stage_metrics(macro, "Before Attack") is not None:
            channel = macro
            channel_name = "Macro"
        else:
            print(
                f"[WARN] {method_key}: no usable Micro/Macro 'Before Attack' "
                f"in {path}"
            )
            continue

        before = get_stage_metrics(channel, "Before Attack")
        if isinstance(before, dict):
            for metric in target_metrics:
                value = safe_float(before.get(metric, np.nan))
                if np.isfinite(value):
                    item[f"Unattacked_{metric}"] = value

        evaluated = data.get("evaluated_attacks", [])
        if not isinstance(evaluated, list) or not evaluated:
            attack_name = data.get("attack_name")
            evaluated = [attack_name] if isinstance(attack_name, str) and attack_name else []

        # Prefer canonical ATTACKS ordering/names, but only fill attacks that
        # are actually represented in this file.
        evaluated_norm = {normalize_stage_name(str(a)): str(a) for a in evaluated}
        for attack in ATTACKS:
            attack_norm = normalize_stage_name(attack)
            if evaluated_norm and attack_norm not in evaluated_norm:
                # Some all-in-one files can omit evaluated_attacks metadata;
                # in that case the stage lookup below is still attempted.
                continue

            stage = get_stage_metrics(channel, f"After {attack}")
            if not isinstance(stage, dict):
                # Handle original spelling/case from evaluated_attacks.
                real_attack = evaluated_norm.get(attack_norm)
                if real_attack:
                    stage = get_stage_metrics(channel, f"After {real_attack}")
            if not isinstance(stage, dict):
                continue

            for metric in target_metrics:
                value = safe_float(stage.get(metric, np.nan))
                if np.isfinite(value):
                    item[f"{attack}_{metric}"] = value

        print(
            f"[METRICS] {method_key}: loaded {channel_name} robustness "
            f"from {path.relative_to(PROJECT_ROOT)}"
        )

    # Require at least the clean metric to regard this as a valid source.
    if not np.isfinite(safe_float(item.get("Unattacked_AUC", np.nan))):
        return None

    return item


