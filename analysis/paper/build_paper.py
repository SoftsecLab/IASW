def stable_split(key: str, cal_ratio: float = 0.5) -> str:
    """
    Deterministic sample-level split for null texts.

    Both human and no-watermark null observations from the same JSONL sample
    receive the same split, avoiding leakage across calibration and test sets.
    """
    h = hashlib.md5(str(key).encode("utf-8")).hexdigest()
    v = int(h[:8], 16) / 0xFFFFFFFF
    return "calibration" if v < cal_ratio else "test"


def extract_dual_channels(det: dict) -> Optional[dict]:
    """
    Extract calibrated Micro/Macro z-scores from one dual detection result.

    The current IAS-W detector may change z_score_macro_calibrated; therefore
    Tables 8-9 are rebuilt from the current JSONL rather than copied from an
    older summary.
    """
    parsed = parse_detection_result(det)
    if not parsed:
        return None

    micro = safe_float(parsed.get("micro"))
    macro = safe_float(parsed.get("macro"))
    if not (np.isfinite(micro) and np.isfinite(macro)):
        return None

    p_micro = float(np.clip(stats.norm.sf(min(float(micro), 37.0)), 1e-300, 1.0))
    p_macro = float(np.clip(stats.norm.sf(min(float(macro), 37.0)), 1e-300, 1.0))
    fisher_chi2 = -2.0 * (math.log(p_micro) + math.log(p_macro))

    return {
        "z_micro": float(micro),
        "z_macro": float(macro),
        "score_fisher": float(fisher_chi2),
        "score_max": float(max(micro, macro)),
    }


def collect_dual_decision_flat(
    cal_ratio: float = 0.5,
    method_key: str = "dual_kgw_iasw",
) -> pd.DataFrame:
    """
    Rebuild the flat score table for every available dataset-model setting
    containing the canonical KGW+IAS-W record.

    label=0:
        detection_human and detection_no_wm
    label=1:
        detection_wm and the nine canonical attacked outputs

    Extra DIPPER-strength variants are intentionally ignored.
    """
    rows = []

    for dataset in DATASETS:
        ds_dir = MAIN_ROOT / dataset
        if not ds_dir.exists():
            continue

        for model_dir in sorted(p for p in ds_dir.iterdir() if p.is_dir()):
            records = discover_record_files(records_dir_of(model_dir))
            path = records.get(method_key)
            if path is None:
                continue

            for obj in load_jsonl(path):
                sample_id = int(obj.get("_line_idx", 0))
                split = stable_split(
                    f"{dataset}-{model_dir.name}-{method_key}-{sample_id}",
                    cal_ratio=cal_ratio,
                )

                for source, det_key in [
                    ("human", "detection_human"),
                    ("no_wm", "detection_no_wm"),
                ]:
                    scored = extract_dual_channels(obj.get(det_key) or {})
                    if scored is None:
                        continue
                    rows.append({
                        "dataset": dataset,
                        "dataset_display": DATASET_DISPLAY.get(dataset, dataset),
                        "model": model_dir.name,
                        "model_display": display_backbone(model_dir.name),
                        "method": method_key,
                        "sample_id": sample_id,
                        "source": source,
                        "attack": "clean",
                        "label": 0,
                        "split": split,
                        "record_file": str(path.relative_to(PROJECT_ROOT)),
                        **scored,
                    })

                scored = extract_dual_channels(obj.get("detection_wm") or {})
                if scored is not None:
                    rows.append({
                        "dataset": dataset,
                        "dataset_display": DATASET_DISPLAY.get(dataset, dataset),
                        "model": model_dir.name,
                        "model_display": display_backbone(model_dir.name),
                        "method": method_key,
                        "sample_id": sample_id,
                        "source": "wm",
                        "attack": "Before Attack",
                        "label": 1,
                        "split": "test",
                        "record_file": str(path.relative_to(PROJECT_ROOT)),
                        **scored,
                    })

                attacks = obj.get("attacks") or {}
                if not isinstance(attacks, dict):
                    continue

                for attack in ATTACKS:
                    atk = attacks.get(attack)
                    if not isinstance(atk, dict):
                        continue
                    scored = extract_dual_channels(
                        atk.get("detection_results") or {}
                    )
                    if scored is None:
                        continue
                    rows.append({
                        "dataset": dataset,
                        "dataset_display": DATASET_DISPLAY.get(dataset, dataset),
                        "model": model_dir.name,
                        "model_display": display_backbone(model_dir.name),
                        "method": method_key,
                        "sample_id": sample_id,
                        "source": "attacked_wm",
                        "attack": attack,
                        "label": 1,
                        "split": "test",
                        "record_file": str(path.relative_to(PROJECT_ROOT)),
                        **scored,
                    })

    out = pd.DataFrame(rows)
    if not out.empty:
        out.to_csv(
            PAPER_CSV / "dual_decision_flat_source.csv",
            index=False,
            encoding="utf-8-sig",
        )
    return out


def empirical_threshold(clean_scores: Iterable[float], alpha: float) -> float:
    arr = np.asarray(finite(clean_scores), dtype=float)
    if len(arr) == 0:
        return np.nan
    try:
        return float(np.quantile(arr, 1.0 - alpha, method="higher"))
    except TypeError:
        return float(np.quantile(arr, 1.0 - alpha, interpolation="higher"))


def safe_rate(values: Iterable[bool]) -> float:
    arr = np.asarray(list(values), dtype=bool)
    return float(np.mean(arr)) if len(arr) else np.nan


def collect_decision_rule_analysis(
    flat_df: pd.DataFrame,
    target_fprs: Tuple[float, ...] = (0.01, 0.05),
) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """
    Compute per-setting/per-attack TPR for Fisher and Max using thresholds
    calibrated on the calibration half of the null samples.

    Returns:
        detailed_df: per setting x fusion x attack x FPR
        table8_df: grouped Fisher-vs-Max win counts and mean deltas
    """
    if flat_df.empty:
        return pd.DataFrame(), pd.DataFrame()

    detailed_rows = []

    for (dataset, model), sub in flat_df.groupby(["dataset", "model"]):
        clean_cal = sub[
            (sub["label"] == 0) & (sub["split"] == "calibration")
        ]
        clean_test = sub[
            (sub["label"] == 0) & (sub["split"] == "test")
        ]
        pos = sub[sub["label"] == 1]

        if clean_cal.empty or clean_test.empty:
            print(
                f"[WARN] decision analysis skipped: empty clean split "
                f"for {dataset}/{model}"
            )
            continue

        for alpha in target_fprs:
            for fusion, score_col in [
                ("Fisher", "score_fisher"),
                ("Max", "score_max"),
            ]:
                thr = empirical_threshold(clean_cal[score_col], alpha)
                emp_fpr = safe_rate(clean_test[score_col].values >= thr)

                for attack in ["Before Attack"] + ATTACKS:
                    atk = pos[pos["attack"] == attack]
                    if atk.empty:
                        continue
                    detailed_rows.append({
                        "dataset": dataset,
                        "model": model,
                        "model_display": display_backbone(model),
                        "fusion": fusion,
                        "attack": attack,
                        "target_fpr": alpha,
                        "threshold": thr,
                        "empirical_fpr": emp_fpr,
                        "tpr": safe_rate(atk[score_col].values >= thr),
                        "positive_n": len(atk),
                        "clean_cal_n": len(clean_cal),
                        "clean_test_n": len(clean_test),
                    })

    detailed = pd.DataFrame(detailed_rows)
    if detailed.empty:
        return detailed, pd.DataFrame()

    detailed.to_csv(
        PAPER_CSV / "decision_rule_source.csv",
        index=False,
        encoding="utf-8-sig",
    )

    summary_rows = []
    group_specs = list(DECISION_GROUPS.items()) + [
        ("Avg.", DECISION_ALL_ATTACKS)
    ]

    for alpha in target_fprs:
        for group_name, attacks in group_specs:
            setting_deltas = []

            settings = detailed[
                detailed["target_fpr"] == alpha
            ][["dataset", "model"]].drop_duplicates()

            fisher_wins = 0
            max_wins = 0
            ties = 0

            for _, setting in settings.iterrows():
                ds = setting["dataset"]
                model = setting["model"]
                block = detailed[
                    (detailed["target_fpr"] == alpha)
                    & (detailed["dataset"] == ds)
                    & (detailed["model"] == model)
                    & (detailed["attack"].isin(attacks))
                ]

                fisher_vals = block[
                    block["fusion"] == "Fisher"
                ]["tpr"].dropna()
                max_vals = block[
                    block["fusion"] == "Max"
                ]["tpr"].dropna()

                if len(fisher_vals) != len(attacks) or len(max_vals) != len(attacks):
                    continue

                f = float(fisher_vals.mean())
                m = float(max_vals.mean())
                d = f - m
                setting_deltas.append(d)

                if d > 1e-12:
                    fisher_wins += 1
                elif d < -1e-12:
                    max_wins += 1
                else:
                    ties += 1

            n = len(setting_deltas)
            summary_rows.append({
                "Metric": f"TPR@{int(round(alpha * 100))}%FPR",
                "target_fpr": alpha,
                "Block": group_name,
                "Fisher Wins": fisher_wins,
                "Max Wins": max_wins,
                "Ties": ties,
                "Settings": n,
                "Delta": float(np.mean(setting_deltas)) if n else np.nan,
            })

    table8 = pd.DataFrame(summary_rows)
    table8.to_csv(
        PAPER_CSV / "decision_rule_grouped_source.csv",
        index=False,
        encoding="utf-8-sig",
    )
    return detailed, table8


def latex_decision_rule_table(df: pd.DataFrame) -> str:
    """
    Build manuscript Table 8 in a compact single-column layout.

    Each numeric cell reports:
        TPR@1%FPR / TPR@5%FPR

    The total number of evaluated dataset-model settings is stated once in the
    caption, so individual win counts are shown as integers rather than x/7.
    Ties are intentionally omitted from the Fisher/Max win columns and are
    explicitly documented in the caption.
    """
    if df.empty:
        return "% Table 8 skipped: no dual decision data.\n"

    block_order = [
        "Surface",
        "Structural",
        "Paraphrase",
        "Translation",
        "Avg.",
    ]

    # Determine the common number of evaluated settings.
    setting_counts = pd.to_numeric(
        df.get("Settings", pd.Series(dtype=float)),
        errors="coerce",
    ).dropna()

    if setting_counts.empty:
        settings_n = 0
    else:
        unique_counts = sorted(set(int(x) for x in setting_counts))
        settings_n = unique_counts[0]
        if len(unique_counts) > 1:
            print(
                "[WARN] Table 8 has different setting counts across rows: "
                f"{unique_counts}. Caption uses {settings_n}."
            )

    def get_row(metric: str, block: str):
        x = df[
            (df["Metric"] == metric)
            & (df["Block"] == block)
        ]
        return None if x.empty else x.iloc[0]

    def pair_int(row1, row5, col: str) -> str:
        if row1 is None or row5 is None:
            return "--"
        return (
            f"{int(row1[col])}"
            + r" \,/\, "
            + f"{int(row5[col])}"
        )

    def pair_delta(row1, row5) -> str:
        if row1 is None or row5 is None:
            return "--"
        d1 = safe_float(row1["Delta"]) * 100.0
        d5 = safe_float(row5["Delta"]) * 100.0
        if not (np.isfinite(d1) and np.isfinite(d5)):
            return "--"
        return (
            f"{d1:+.2f}"
            + r" \,/\, "
            + f"{d5:+.2f}"
        )

    settings_text = (
        f"{settings_n} dataset-model settings"
        if settings_n > 0
        else "the available dataset-model settings"
    )

    lines = [
        r"\begin{table}[t]",
        r"\centering",
        r"\scriptsize",
        r"\setlength{\tabcolsep}{4.0pt}",
        r"\renewcommand{\arraystretch}{1.05}",
        (
            r"\caption{Comparison of final decision rules across "
            + settings_text
            + r". Each cell reports TPR@1\%FPR / TPR@5\%FPR. "
            r"$\Delta$ denotes the mean improvement of Fisher-style "
            r"aggregation over Max aggregation in percentage points. "
            r"Ties are omitted from the win counts. "
            r"Surface: Typo/Drop/Swap; Structural: Del-Ins/Copy-Paste; "
            r"Paraphrase: PEGASUS/DIPPER; Translation: BackTrans; "
            r"Avg. includes all nine attacks.}"
        ),
        r"\label{tab:kgw_ias_fusion_stability}",
        r"\begin{tabular}{lccc}",
        r"\toprule",
        r"Block & Fisher Wins & Max Wins & $\Delta$ \\",
        r"\midrule",
    ]

    for block in block_order:
        row1 = get_row("TPR@1%FPR", block)
        row5 = get_row("TPR@5%FPR", block)

        lines.append(
            f"{block} & "
            f"{pair_int(row1, row5, 'Fisher Wins')} & "
            f"{pair_int(row1, row5, 'Max Wins')} & "
            f"{pair_delta(row1, row5)} "
            + r"\\"
        )

    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
    ]

    return "\n".join(lines) + "\n"



def collect_null_corr_fpr(
    flat_df: pd.DataFrame,
    target_fpr: float = 0.01,
) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """
    Recompute Table 9 from the CURRENT calibrated Micro/Macro scores.

    Correlations use all available clean/null samples in each setting.
    Empirical FPR uses a Fisher threshold fit on the calibration split and
    evaluated on the held-out null split.
    """
    if flat_df.empty:
        return pd.DataFrame(), pd.DataFrame()

    rows = []

    for (dataset, model), sub in flat_df.groupby(["dataset", "model"]):
        clean_all = sub[sub["label"] == 0]
        clean_cal = sub[
            (sub["label"] == 0) & (sub["split"] == "calibration")
        ]
        clean_test = sub[
            (sub["label"] == 0) & (sub["split"] == "test")
        ]

        if clean_cal.empty or clean_test.empty:
            continue

        pearson = clean_all[["z_micro", "z_macro"]].corr(
            method="pearson"
        ).iloc[0, 1]
        spearman = clean_all[["z_micro", "z_macro"]].corr(
            method="spearman"
        ).iloc[0, 1]

        thr = empirical_threshold(clean_cal["score_fisher"], target_fpr)
        emp_fpr = safe_rate(clean_test["score_fisher"].values >= thr)

        rows.append({
            "dataset": dataset,
            "dataset_display": DATASET_DISPLAY.get(dataset, dataset),
            "model": model,
            "model_display": display_backbone(model),
            "Pearson r": pearson,
            "Spearman rho": spearman,
            "Emp. FPR": emp_fpr,
            "clean_n": len(clean_all),
            "clean_cal_n": len(clean_cal),
            "clean_test_n": len(clean_test),
            "threshold": thr,
        })

    setting_df = pd.DataFrame(rows)
    if setting_df.empty:
        return setting_df, pd.DataFrame()

    setting_df.to_csv(
        PAPER_CSV / "null_corr_fpr_settings_source.csv",
        index=False,
        encoding="utf-8-sig",
    )

    def pack(col):
        vals = setting_df[col].astype(float)
        return {
            "Mean": float(vals.mean()),
            "Std": float(vals.std(ddof=1)) if len(vals) > 1 else np.nan,
            "Min": float(vals.min()),
            "Max": float(vals.max()),
        }

    summary_rows = []
    for label, col in [
        ("Pearson $r$", "Pearson r"),
        ("Spearman $\\rho$", "Spearman rho"),
        ("Emp. FPR", "Emp. FPR"),
    ]:
        p = pack(col)
        summary_rows.append({
            "Metric": label,
            **p,
            "Settings": len(setting_df),
        })

    summary = pd.DataFrame(summary_rows)
    summary.to_csv(
        PAPER_CSV / "null_corr_fpr_source.csv",
        index=False,
        encoding="utf-8-sig",
    )
    return setting_df, summary


