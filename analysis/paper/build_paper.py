def collect_efficiency() -> pd.DataFrame:
    """
    Collect raw generation times for every available dataset-model-method run.

    The manuscript efficiency table aggregates all available formal settings
    for each method (rather than showing C4/Llama-3.1 only). The resulting
    source CSV contains one row per method after pooling valid per-sample
    generation times across all matching runs.
    """
    table_methods = efficiency_methods()

    buckets = {
        m: {
            "times": [],
            "total_n": 0,
            "runs": [],
        }
        for m in table_methods
    }

    for dataset in DATASETS:
        ds_dir = MAIN_ROOT / dataset
        if not ds_dir.exists():
            continue

        for model_dir in sorted(p for p in ds_dir.iterdir() if p.is_dir()):
            records = discover_record_files(records_dir_of(model_dir))

            for method_key in table_methods:
                path = records.get(method_key)
                if path is None:
                    continue

                run_total = 0
                run_valid = 0

                for obj in load_jsonl(path):
                    run_total += 1
                    value = obj.get(
                        "generation_time",
                        obj.get("time_cost_seconds"),
                    )
                    fv = safe_float(value)
                    if np.isfinite(fv) and fv >= 0:
                        buckets[method_key]["times"].append(float(fv))
                        run_valid += 1

                buckets[method_key]["total_n"] += run_total
                buckets[method_key]["runs"].append(
                    f"{dataset}/{model_dir.name}:{run_valid}/{run_total}"
                )

    rows = []
    for method_key in table_methods:
        pack = buckets[method_key]
        arr = np.asarray(pack["times"], dtype=float)
        total_n = int(pack["total_n"])
        valid_n = int(len(arr))

        rows.append({
            "method_key": method_key,
            "Method": display_method(method_key),
            "total_n": total_n,
            "valid_n": valid_n,
            "success_rate": valid_n / total_n if total_n else np.nan,
            "mean": float(np.mean(arr)) if valid_n else np.nan,
            "median": float(np.median(arr)) if valid_n else np.nan,
            "q1": float(np.percentile(arr, 25)) if valid_n else np.nan,
            "q3": float(np.percentile(arr, 75)) if valid_n else np.nan,
            "max": float(np.max(arr)) if valid_n else np.nan,
            "runs": " | ".join(pack["runs"]),
        })

    df = pd.DataFrame(rows)
    df.to_csv(
        PAPER_CSV / "efficiency_source.csv",
        index=False,
        encoding="utf-8-sig",
    )
    return df


def latex_efficiency(df: pd.DataFrame) -> str:
    """
    Match manuscript generation-efficiency table.
    """
    if df.empty:
        return "% Efficiency table skipped: no records.\n"

    table_methods = efficiency_methods()

    base = df[df["method_key"] == "kgw"]
    kgw_median = (
        safe_float(base.iloc[0]["median"])
        if not base.empty
        else np.nan
    )

    lines = [
        r"\begin{table}[t]",
        r"\makeatletter",
        r"\long\def\@makecaption#1#2{%",
        r"  \vskip 2pt",
        r"  \noindent",
        r"  \parbox{\linewidth}{%",
        r"    \small",
        r"    \textbf{#1}\quad #2%",
        r"  }%",
        r"  \vskip 2pt",
        r"}",
        r"\makeatother",
        r"\centering",
        r"\small",
        r"\setlength{\tabcolsep}{4pt}",
        r"\caption{Generation efficiency summary. Runtime is reported in seconds per sample. Rel. denotes runtime relative to KGW.}",
        r"\label{tab:efficiency_compact}",
        r"\resizebox{\linewidth}{!}{",
        r"\begin{tabular}{lccccc}",
        r"\toprule",
        r"Method & Valid & Success Rate & Median [Q1, Q3] & Max & Rel. \\",
        r"\midrule",
    ]

    for method in table_methods:
        x = df[df["method_key"] == method]
        if x.empty:
            continue
        row = x.iloc[0]

        valid_n = int(row["valid_n"])
        total_n = int(row["total_n"])
        success = safe_float(row["success_rate"]) * 100.0
        median = safe_float(row["median"])
        q1 = safe_float(row["q1"])
        q3 = safe_float(row["q3"])
        mx = safe_float(row["max"])
        rel = (
            median / kgw_median
            if np.isfinite(median)
            and np.isfinite(kgw_median)
            and kgw_median > 0
            else np.nan
        )

        valid_text = f"{valid_n}/{total_n}" if total_n > 0 else "--"
        success_text = f"{success:.1f}\\%" if np.isfinite(success) else "--"
        runtime_text = (
            f"{median:.2f} [{q1:.2f}, {q3:.2f}]"
            if np.isfinite(median) and np.isfinite(q1) and np.isfinite(q3)
            else "--"
        )
        max_text = f"{mx:.2f}" if np.isfinite(mx) else "--"
        rel_text = f"{rel:.2f}$\\times$" if np.isfinite(rel) else "--"

        lines.append(
            f"{display_method(method)} & "
            f"{valid_text} & "
            f"{success_text} & "
            f"{runtime_text} & "
            f"{max_text} & "
            f"{rel_text} "
            + r"\\"
        )

    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"}",
        r"\end{table}",
    ]
    return "\n".join(lines) + "\n"


