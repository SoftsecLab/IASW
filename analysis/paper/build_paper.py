def has_dot_degeneration(text: str, threshold: int = 10) -> bool:
    if not isinstance(text, str):
        return False
    return "." * threshold in text


def quality_values_from_record(row: dict) -> Optional[dict]:
    if has_dot_degeneration(row.get("wm_text", ""), threshold=10):
        return None

    q = row.get("quality") or {}
    wm = q.get("wm") or {}
    sem = q.get("semantic") or {}

    return {
        "PPL": safe_float(wm.get("ppl")),
        "Entropy": safe_float(wm.get("ent3")),
        "Repetition": safe_float(wm.get("rep15")),
        "Coherence": safe_float(sem.get("sim_wm_vs_human")),
        "SimClean": safe_float(sem.get("sim_wm_vs_clean")),
    }


def load_mauve_from_summary(
    dataset: str,
    model: str,
    method_key: str,
) -> float:
    """
    MAUVE is not stored per-sample in current JSONL.
    Keep a narrow fallback to final_quality_summary.csv only for MAUVE.
    """
    path = (
        MAIN_ROOT
        / dataset
        / model
        / "summaries"
        / "final_quality_summary.csv"
    )
    if not path.exists():
        return np.nan

    try:
        df = pd.read_csv(
            path,
            na_values=["-", ""],
            encoding="utf-8-sig",
        )
    except Exception:
        return np.nan

    if "Method" not in df.columns or "MAUVE" not in df.columns:
        return np.nan

    names = df["Method"].astype(str).str.strip().str.lower()

    # Old summaries may include suffixes such as " (Fisher Fusion)".
    if method_key.startswith("dual_"):
        mask = names.str.startswith(method_key.lower()) & names.str.contains("fisher", regex=False)
        if not mask.any():
            mask = names.str.startswith(method_key.lower())
    else:
        mask = names == method_key.lower()

    if not mask.any():
        return np.nan

    return safe_float(df.loc[mask, "MAUVE"].iloc[0])


def collect_quality() -> pd.DataFrame:
    rows = []

    for dataset in DATASETS:
        ds_dir = MAIN_ROOT / dataset
        if not ds_dir.exists():
            continue

        for model_dir in sorted(p for p in ds_dir.iterdir() if p.is_dir()):
            records = discover_record_files(records_dir_of(model_dir))

            for method_key, path in records.items():
                buckets = {
                    "PPL": [],
                    "Entropy": [],
                    "Repetition": [],
                    "Coherence": [],
                    "SimClean": [],
                }
                total = 0
                kept = 0

                for obj in load_jsonl(path):
                    total += 1
                    vals = quality_values_from_record(obj)
                    if vals is None:
                        continue
                    kept += 1
                    for key, value in vals.items():
                        if np.isfinite(value):
                            buckets[key].append(value)

                item = {
                    "dataset": dataset,
                    "model": model_dir.name,
                    "method_key": method_key,
                    "Method": display_method(method_key),
                    "record_file": str(path.relative_to(PROJECT_ROOT)),
                    "total_n": total,
                    "kept_n": kept,
                    "filtered_n": total - kept,
                    "PPL": mean_or_nan(buckets["PPL"]),
                    "Entropy": mean_or_nan(buckets["Entropy"]),
                    "Repetition": mean_or_nan(buckets["Repetition"]),
                    "Coherence": mean_or_nan(buckets["Coherence"]),
                    "SimClean": mean_or_nan(buckets["SimClean"]),
                    "MAUVE": load_mauve_from_summary(
                        dataset,
                        model_dir.name,
                        method_key,
                    ),
                }
                rows.append(item)

    df = pd.DataFrame(rows)
    if not df.empty:
        df.to_csv(
            PAPER_CSV / "quality_source.csv",
            index=False,
            encoding="utf-8-sig",
        )
    return df



