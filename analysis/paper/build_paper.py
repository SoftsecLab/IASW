def collect_dual_combo(robustness_df: pd.DataFrame) -> pd.DataFrame:
    """Build channel-combination grouped robustness for all three metrics."""
    if robustness_df.empty:
        return pd.DataFrame()

    sub = robustness_df[
        (robustness_df["dataset"] == "c4")
        & (robustness_df["model"] == PRIMARY_MODEL)
    ].copy()

    methods = [
        "kgw",
        "dual_kgw_iasw",
        "dual_kgw_semstamp",
        "dual_kgw_ksemstamp",
        "iasw",
        "dual_sweet_iasw",
        "dual_dipmark_iasw",
    ]
    groups = {
        "Surface": ["typo", "drop", "swap"],
        "Structural": ["del_ins", "copy_paste", "sentence_reorder"],
        "Paraphrase": ["pegasus", "dipper"],
        "Translation": ["back_translation"],
    }
    all_attacks = sum(groups.values(), [])

    def group_mean(row, attacks, metric_key):
        return mean_or_nan([
            safe_float(row.get(f"{a}_{metric_key}", np.nan))
            for a in attacks
        ])

    rows = []
    for metric_key, metric_label, metric_suffix in ROBUSTNESS_METRICS:
        for method in methods:
            x = sub[sub["method_key"] == method]
            if x.empty:
                continue
            row = x.iloc[0]
            item = {
                "metric": metric_key,
                "metric_label": metric_label,
                "metric_suffix": metric_suffix,
                "method_key": method,
            }
            for group_name, attacks in groups.items():
                item[group_name] = group_mean(row, attacks, metric_key)
            item["Avg."] = group_mean(row, all_attacks, metric_key)
            rows.append(item)

    out = pd.DataFrame(rows)
    out.to_csv(
        PAPER_CSV / "dual_combo_source.csv",
        index=False,
        encoding="utf-8-sig",
    )
    return out

def latex_dual_combo(df: pd.DataFrame) -> str:
    """Generate AUROC, TPR@1%FPR, and TPR@5%FPR channel-combination tables."""
    if df.empty:
        return "% Channel-combination table skipped: no source data.\n"

    display = {
        "kgw": "KGW",
        "dual_kgw_iasw": "KGW+IASW",
        "dual_kgw_semstamp": "KGW+SS",
        "dual_kgw_ksemstamp": "KGW+kSS",
        "iasw": "IASW",
        "dual_sweet_iasw": "Sweet+IASW",
        "dual_dipmark_iasw": "DiP+IASW",
    }
    fixed_kgw = [
        "kgw", "dual_kgw_iasw", "dual_kgw_semstamp", "dual_kgw_ksemstamp",
    ]
    fixed_iasw = ["iasw", "dual_kgw_iasw", "dual_sweet_iasw", "dual_dipmark_iasw"]
    cols = ["Surface", "Structural", "Paraphrase", "Translation", "Avg."]
    blocks = []

    for metric_key, metric_label, metric_suffix in ROBUSTNESS_METRICS:
        metric_df = df[df["metric"] == metric_key].copy() if "metric" in df.columns else df.copy()

        def block_ranks(methods):
            ranks = {}
            for col in cols:
                vals = []
                for method in methods:
                    x = metric_df[metric_df["method_key"] == method]
                    if x.empty:
                        continue
                    v = safe_float(x.iloc[0][col])
                    if np.isfinite(v):
                        vals.append(round(v * 100.0, 1))
                ranks[col] = max(vals) if vals else np.nan
            return ranks

        def render(method, col, ranks):
            x = metric_df[metric_df["method_key"] == method]
            if x.empty:
                return "--"
            v = safe_float(x.iloc[0][col])
            if not np.isfinite(v):
                return "--"
            p = round(v * 100.0, 1)
            text = f"{p:.1f}"
            return rf"\textbf{{{text}}}" if np.isfinite(ranks[col]) and p == ranks[col] else text

        rank_kgw = block_ranks(fixed_kgw)
        rank_iasw = block_ranks(fixed_iasw)
        lines = [
            r"\begin{table}[t]",
            r"\centering",
            r"\scriptsize",
            r"\setlength{\tabcolsep}{2.6pt}",
            r"\begin{tabular}{@{}lccccc@{}}",
            r"\toprule",
            r"Method & Surface & Structural & Paraphrase & Translation & Avg. \\",
            r"\midrule",
            r"\multicolumn{6}{@{}l}{\textit{Fixed KGW}} \\",
        ]
        for method in fixed_kgw:
            vals = [render(method, c, rank_kgw) for c in cols]
            lines.append(f"{display[method]} & " + " & ".join(vals) + r" \\")
        lines += [
            r"\midrule",
            r"\multicolumn{6}{@{}l}{\textit{Fixed IASW}} \\",
        ]
        for method in fixed_iasw:
            vals = [render(method, c, rank_iasw) for c in cols]
            lines.append(f"{display[method]} & " + " & ".join(vals) + r" \\")
        lines += [
            r"\bottomrule",
            r"\end{tabular}",
            rf"\caption{{Channel combination ablation on C4/RealNews with Llama-3.1-8B-Instruct measured by {metric_label}. Surface: Typo/Drop/Swap; Structural: Del-Ins/Copy-Paste/Sent-Reorder; Paraphrase: PEGASUS/DIPPER; Translation: BackTrans; Avg. includes all nine attacked settings.}}",
            rf"\label{{tab:ablation_combinations_{metric_suffix}}}",
            r"\end{table}",
        ]
        blocks.append("\n".join(lines))

    return "\n\n".join(blocks) + "\n"

def collect_fusion_ablation() -> pd.DataFrame:
    """
    Reconstruct KGW+IAS-W channel/fusion metrics from the primary C4 record.

    Prefer the canonical ``dual_kgw_iasw.jsonl`` record. If that exact file is
    absent, fall back to the preferred parameterized file selected by
    ``discover_record_files``.
    """
    path = (
        MAIN_ROOT
        / "c4"
        / PRIMARY_MODEL
        / "records"
        / "dual_kgw_iasw.jsonl"
    )

    if not path.exists():
        records = discover_record_files(path.parent)
        path = records.get("dual_kgw_iasw")
        if path is None:
            return pd.DataFrame()

    channels = {
        "Word-level": {"neg": [], "wm": [], "atk": {a: [] for a in ATTACKS}},
        "Semantic-level": {"neg": [], "wm": [], "atk": {a: [] for a in ATTACKS}},
        "Max Fusion": {"neg": [], "wm": [], "atk": {a: [] for a in ATTACKS}},
        "Fisher Fusion": {"neg": [], "wm": [], "atk": {a: [] for a in ATTACKS}},
    }

    def channel_scores(res):
        p = parse_detection_result(res)
        if not p:
            return None
        mx = (
            p["max"]
            if np.isfinite(p["max"])
            else (
                max(p["micro"], p["macro"])
                if np.isfinite(p["micro"]) and np.isfinite(p["macro"])
                else np.nan
            )
        )
        fish = (
            p["fisher"]
            if np.isfinite(p["fisher"])
            else fisher_fusion(p["micro"], p["macro"])
        )
        return {
            "Word-level": p["micro"],
            "Semantic-level": p["macro"],
            "Max Fusion": mx,
            "Fisher Fusion": fish,
        }

    for obj in load_jsonl(path):
        neg_res = obj.get("detection_human") or obj.get("detection_no_wm") or {}
        wm_res = obj.get("detection_wm") or {}
        neg = channel_scores(neg_res)
        wm = channel_scores(wm_res)
        if neg:
            for name, value in neg.items():
                if np.isfinite(value):
                    channels[name]["neg"].append(value)
        if wm:
            for name, value in wm.items():
                if np.isfinite(value):
                    channels[name]["wm"].append(value)

        attacks = obj.get("attacks") or {}
        for attack in ATTACKS:
            data = attacks.get(attack)
            if not isinstance(data, dict):
                continue
            scored = channel_scores(data.get("detection_results") or {})
            if not scored:
                continue
            for name, value in scored.items():
                if np.isfinite(value):
                    channels[name]["atk"][attack].append(value)

    rows = []
    for name, pack in channels.items():
        item = {"Channel": name}
        base = detection_metrics(pack["neg"], pack["wm"])
        for metric_key, _, _ in ROBUSTNESS_METRICS:
            item[f"Unattacked_{metric_key}"] = base[metric_key]
            attacked_vals = []
            for attack in ATTACKS:
                m = detection_metrics(pack["neg"], pack["atk"][attack])
                item[f"{attack}_{metric_key}"] = m[metric_key]
                if np.isfinite(m[metric_key]):
                    attacked_vals.append(m[metric_key])
            item[f"Avg_Attacked_{metric_key}"] = (
                float(np.mean(attacked_vals)) if attacked_vals else np.nan
            )
        rows.append(item)

    df = pd.DataFrame(rows)
    df.to_csv(PAPER_CSV / "fusion_ablation_source.csv", index=False, encoding="utf-8-sig")
    return df

def latex_fusion_ablation(df: pd.DataFrame) -> str:
    if df.empty:
        return "% Fusion ablation table skipped: no dual KGW+IAS-W records.\n"

    blocks = []
    for metric_key, metric_label, metric_suffix in ROBUSTNESS_METRICS:
        lines = [
            r"\begin{table}[htbp]",
            r"\centering",
            r"\small",
            rf"\caption{{Channel and fusion ablation for KGW+IAS-W on C4 measured by {metric_label} (\%).}}",
            rf"\label{{tab:fusion_ablation_{metric_suffix}}}",
            r"\begin{tabular}{lcc}",
            r"\toprule",
            r"Statistic & Unattacked & Avg. attacked \\",
            r"\midrule",
        ]
        for _, row in df.iterrows():
            lines.append(
                f"{latex_escape(row['Channel'])} & "
                f"{fmt(row[f'Unattacked_{metric_key}'], 1, True)} & "
                f"{fmt(row[f'Avg_Attacked_{metric_key}'], 1, True)} " + r"\\"
            )
        lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
        blocks.append("\n".join(lines))
    return "\n\n".join(blocks) + "\n"

