    # Table 3: quality
    # -----------------------------------------------------------------
    if args.only in {"all", "quality"}:
        print("[2] Rebuild Table 3 text quality...")
        quality_df = collect_quality()
        table3_tex = latex_quality(
            quality_df
        )

        write_tex(
            TABLE_TEX_FILES[3],
            table3_tex,
        )

    # -----------------------------------------------------------------
    # Table 4: efficiency
    # -----------------------------------------------------------------
    if args.only in {"all", "efficiency"}:
        print("[3] Rebuild Table 4 efficiency...")
        efficiency_df = collect_efficiency()
        table4_tex = latex_efficiency(
            efficiency_df
        )

        write_tex(
            TABLE_TEX_FILES[4],
            table4_tex,
        )

    # -----------------------------------------------------------------
    # Parameter-ablation CSV sources + supplementary fusion table
    # -----------------------------------------------------------------
    if args.only in {"all", "ablation"}:
        print(
            "[4] Rebuild parameter-ablation sources "
            "and supplementary fusion table..."
        )

        fusion_df = collect_fusion_ablation()
        fusion_tex = latex_fusion_ablation(
            fusion_df
        )
        write_tex(
            AUX_TEX_FILES["fusion"],
            fusion_tex,
        )

        build_parameter_ablation_sources()

    # -----------------------------------------------------------------
    # Tables 8-9: final decision and empirical null analysis
    # -----------------------------------------------------------------
    if args.only in {"all", "fusion"}:
        print(
            "[5] Rebuild Tables 8-9 "
            "Fisher/Max and null-FPR analyses..."
        )

        table8_tex, table9_tex = (
            build_final_decision_tables()
        )

        write_tex(
            TABLE_TEX_FILES[8],
            table8_tex,
        )
        write_tex(
            TABLE_TEX_FILES[9],
            table9_tex,
        )

    # -----------------------------------------------------------------
    # Table 6 + supplementary attack-quality table
    # -----------------------------------------------------------------
    if args.only in {"all", "special"}:
        print(
            "[6] Rebuild Table 6 alignment ablation "
            "and attack-quality auxiliary table..."
        )

        attack_tex, _ = (
            build_attack_quality_table()
        )
        table6_tex, _ = (
            build_alignment_table()
        )

        write_tex(
            AUX_TEX_FILES["attack_quality"],
            attack_tex,
        )
        write_tex(
            TABLE_TEX_FILES[6],
            table6_tex,
        )

    write_manifest()

    print("")
    print("[DONE] Canonical manuscript tables:")
    for number in sorted(TABLE_TEX_FILES):
        path = PAPER_LATEX / TABLE_TEX_FILES[number]
        status = "OK" if path.exists() else "not rebuilt in this mode"
        print(
            f"  Table {number:>2}: "
            f"{path.name} [{status}]"
        )

    print("")
    print("[NOTE] Table 5 and Appendix Tables 10-11 are not generated here.")
    print(f"[DONE] CSV audit sources: {PAPER_CSV}")
    print(f"[DONE] Figures: {PAPER_FIGURES}")


