def safe_float(x) -> float:
    try:
        v = float(x)
        return v if np.isfinite(v) else np.nan
    except Exception:
        return np.nan


def finite(values: Iterable[float]) -> List[float]:
    out = []
    for v in values:
        fv = safe_float(v)
        if np.isfinite(fv):
            out.append(float(fv))
    return out


def mean_or_nan(values: Iterable[float]) -> float:
    vals = finite(values)
    return float(np.mean(vals)) if vals else np.nan


def latex_escape(text: str) -> str:
    s = str(text)
    for a, b in [
        ("\\", r"\textbackslash{}"),
        ("&", r"\&"),
        ("%", r"\%"),
        ("_", r"\_"),
        ("#", r"\#"),
    ]:
        s = s.replace(a, b)
    return s


def fmt(x, digits=1, percent=True) -> str:
    v = safe_float(x)
    if not np.isfinite(v):
        return "--"
    if percent:
        if abs(v) <= 1.5:
            v *= 100.0
        return f"{v:.{digits}f}"
    return f"{v:.{digits}f}"


def load_jsonl(path: Path) -> List[dict]:
    rows = []
    with path.open("r", encoding="utf-8", errors="replace") as f:
        for line_idx, line in enumerate(f):
            line = line.strip()
            if not line:
                continue
            try:
                obj = json.loads(line)
            except Exception:
                continue
            if isinstance(obj, dict):
                obj["_line_idx"] = line_idx
                rows.append(obj)
    return rows


def method_key_from_stem(stem: str) -> str:
    """
    Convert a record filename to a paper method family.

    Main-experiment directories sometimes contain parameterized IAS-W files.
    Exact canonical names are preferred by discover_record_files(); this
    function only supplies a stable family label.
    """
    s = stem.strip()

    known = sorted(
        METHOD_DISPLAY,
        key=len,
        reverse=True,
    )
    for key in known:
        if s == key:
            return key
        if s.startswith(key + "_"):
            return key

    # General dual family fallback.
    m = re.match(
        r"^(dual_(?:kgw|sweet|dipmark)_(?:iasw|semstamp|ksemstamp|simmark_cosine|simmark_euclidean))",
        s,
    )
    if m:
        return m.group(1)

    return s


def discover_record_files(records_dir: Path) -> Dict[str, Path]:
    """
    Return one preferred JSONL file per method family.

    Preference:
      1. exact canonical stem (e.g. iasw.jsonl);
      2. otherwise the shortest filename in the family.

    This prevents a parameterized rerun from silently replacing the canonical
    paper record when both are present.
    """
    candidates: Dict[str, List[Path]] = {}

    if not records_dir.exists():
        return {}

    for p in sorted(records_dir.glob("*.jsonl")):
        stem = p.stem
        if stem.startswith(("baseline", "attacked", "detect", "temp", "detailed_quality")):
            continue
        key = method_key_from_stem(stem)
        candidates.setdefault(key, []).append(p)

    selected = {}
    for key, paths in candidates.items():
        exact = [p for p in paths if p.stem == key]
        selected[key] = exact[0] if exact else sorted(paths, key=lambda x: (len(x.stem), x.stem))[0]

    return selected


