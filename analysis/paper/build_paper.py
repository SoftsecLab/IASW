def parse_detection_result(res: dict):
    if not isinstance(res, dict) or not res or "error" in res:
        return None

    z_micro = safe_float(res.get("z_score_micro", np.nan))
    if not np.isfinite(z_micro):
        z_micro = safe_float(
            (res.get("micro") or {}).get("z_score", np.nan)
        )

    z_macro_raw = safe_float(res.get("z_score_macro", np.nan))
    if not np.isfinite(z_macro_raw):
        z_macro_raw = safe_float(
            (res.get("macro") or {}).get("z_score", np.nan)
        )

    z_macro_calib = safe_float(
        res.get("z_score_macro_calibrated", z_macro_raw)
    )

    z_max = safe_float(res.get("z_score_max", np.nan))
    z_fisher = safe_float(res.get("z_score_fisher", np.nan))

    return {
        "micro": z_micro,
        "macro_raw": z_macro_raw,
        "macro": z_macro_calib,
        "max": z_max,
        "fisher": z_fisher,
    }


def fisher_fusion(micro: float, macro: float) -> float:
    if not np.isfinite(micro) or not np.isfinite(macro):
        return np.nan

    z_micro = min(float(micro), 37.0)
    z_macro = min(float(macro), 37.0)

    p_micro = np.clip(stats.norm.sf(z_micro), 1e-300, 1.0)
    p_macro = np.clip(stats.norm.sf(z_macro), 1e-300, 1.0)

    chi2_score = -2.0 * math.log(p_micro) - 2.0 * math.log(p_macro)
    p_fisher = np.clip(
        stats.chi2.sf(chi2_score, df=4),
        1e-300,
        1.0 - 1e-16,
    )
    return float(stats.norm.isf(p_fisher))


def choose_score(parsed: Optional[dict], method_key: str) -> float:
    if not parsed:
        return np.nan

    if method_key.startswith("dual_"):
        if np.isfinite(parsed["fisher"]):
            return float(parsed["fisher"])
        return fisher_fusion(parsed["micro"], parsed["macro"])

    # Single token-level methods normally populate micro.
    if method_key in {"kgw", "sta", "sweet", "dipmark"}:
        return float(parsed["micro"]) if np.isfinite(parsed["micro"]) else np.nan

    # Single semantic methods normally populate macro.
    if method_key in {
        "iasw",
        "semstamp",
        "ksemstamp",
        "simmark_cosine",
        "simmark_euclidean",
    }:
        return float(parsed["macro"]) if np.isfinite(parsed["macro"]) else np.nan

    # Unknown method: choose the non-empty channel conservatively.
    if np.isfinite(parsed["fisher"]):
        return float(parsed["fisher"])
    if np.isfinite(parsed["macro"]):
        return float(parsed["macro"])
    return float(parsed["micro"]) if np.isfinite(parsed["micro"]) else np.nan


def extract_detection_scores(
    path: Path,
    method_key: str,
    negative_source: str = "human",
) -> Tuple[List[float], List[float], Dict[str, List[float]]]:
    negatives = []
    wm = []
    attacks = {a: [] for a in ATTACKS}

    for row in load_jsonl(path):
        if negative_source == "human":
            neg_res = row.get("detection_human") or {}
            if not neg_res:
                neg_res = row.get("detection_no_wm") or {}
        else:
            neg_res = row.get("detection_no_wm") or {}
            if not neg_res:
                neg_res = row.get("detection_human") or {}

        neg_score = choose_score(
            parse_detection_result(neg_res),
            method_key,
        )
        wm_score = choose_score(
            parse_detection_result(row.get("detection_wm") or {}),
            method_key,
        )

        if np.isfinite(neg_score):
            negatives.append(neg_score)
        if np.isfinite(wm_score):
            wm.append(wm_score)

        atk_pack = row.get("attacks") or {}
        if isinstance(atk_pack, dict):
            for attack in ATTACKS:
                data = atk_pack.get(attack)
                if not isinstance(data, dict):
                    continue
                score = choose_score(
                    parse_detection_result(data.get("detection_results") or {}),
                    method_key,
                )
                if np.isfinite(score):
                    attacks[attack].append(score)

    return negatives, wm, attacks


def detection_metrics(
    negatives: Iterable[float],
    positives: Iterable[float],
) -> Dict[str, float]:
    neg = np.asarray(finite(negatives), dtype=float)
    pos = np.asarray(finite(positives), dtype=float)

    if len(neg) == 0 or len(pos) == 0:
        return {
            "TPR@0.1%FPR": np.nan,
            "TPR@1%FPR": np.nan,
            "TPR@5%FPR": np.nan,
            "AUC": np.nan,
        }

    y_true = np.concatenate([
        np.zeros(len(neg), dtype=int),
        np.ones(len(pos), dtype=int),
    ])
    scores = np.concatenate([neg, pos])

    fpr, tpr, _ = roc_curve(y_true, scores)

    out = {"AUC": float(auc(fpr, tpr))}
    for target, label in [
        (0.001, "TPR@0.1%FPR"),
        (0.01, "TPR@1%FPR"),
        (0.05, "TPR@5%FPR"),
    ]:
        idx = np.where(fpr <= target)[0]
        out[label] = float(tpr[idx[-1]]) if len(idx) else 0.0

    return out


def summarize_record_file(
    path: Path,
    method_key: str,
    negative_source: str = "human",
) -> Dict[str, float]:
    negatives, wm, attacked = extract_detection_scores(
        path,
        method_key=method_key,
        negative_source=negative_source,
    )

    row = {
        "method_key": method_key,
        "Method": display_method(method_key),
        "record_file": str(path.relative_to(PROJECT_ROOT)),
        "negative_n": len(negatives),
        "wm_n": len(wm),
    }

    base = detection_metrics(negatives, wm)
    for metric, value in base.items():
        row[f"Unattacked_{metric}"] = value

    for attack in ATTACKS:
        vals = attacked.get(attack, [])
        m = detection_metrics(negatives, vals)
        row[f"{attack}_n"] = len(vals)
        for metric, value in m.items():
            row[f"{attack}_{metric}"] = value

    return row


def avg_attacked_metric(row: pd.Series | dict, metric: str) -> float:
    vals = []
    for attack in ATTACKS:
        v = safe_float(row.get(f"{attack}_{metric}", np.nan))
        if np.isfinite(v):
            vals.append(v)
    return float(np.mean(vals)) if vals else np.nan


