"""
Build paper tables/figures from IASW experiment outputs.

Design goal
-----------
Keep the paper-side code simple:
    - one Python file;
    - one shell entry point;
    - read raw JSONL whenever ordinary robustness/quality/efficiency
      can be reconstructed directly;
    - read results/analysis only for genuinely special analyses
      (attack-quality / IAS-W alignment / mechanism outputs).

This script intentionally does NOT depend on final_robustness_summary.csv
for ordinary detection metrics. That avoids stale-summary problems after
re-detection.

MAUVE is the only ordinary quality field that may still be read from
final_quality_summary.csv because recomputing MAUVE is expensive and it is
not stored per sample in the JSONL records.

Outputs
-------
Canonical manuscript-facing LaTeX files are numbered to match the current
paper:

paper/latex/
    table01_main_robustness.tex
    table02_backbone_summary.tex
    table03_text_quality.tex
    table04_efficiency.tex
    table06_alignment_ablation.tex
    table07_channel_combination.tex
    table08_decision_rule.tex
    table09_null_corr_fpr.tex

Table 5 (stage-wise generation interaction) and Appendix Tables 10-11 are
generated by their dedicated mechanism-analysis scripts and are intentionally
not duplicated here.

Auxiliary / supplementary outputs:
    supp_fusion_ablation.tex
    supp_attack_quality.tex
    generated_tables_manifest.txt

paper/csv/
    main_robustness_source.csv
    cross_backbone_source.csv
    quality_source.csv
    efficiency_source.csv
    fusion_ablation_source.csv
    dual_combo_source.csv
    attack_quality_source.csv
    alignment_ablation_source.csv
    decision_rule_source.csv
    decision_rule_grouped_source.csv
    null_corr_fpr_settings_source.csv
    null_corr_fpr_source.csv
    candidate_ablation_source.csv
    token_length_ablation_source.csv

Figures are generated separately by:
    analysis/paper/plot_parameter_ablation.py

Usage
-----
    python analysis/paper/build_paper.py
    python analysis/paper/build_paper.py --only robustness
    python analysis/paper/build_paper.py --only quality
    python analysis/paper/build_paper.py --only efficiency
    python analysis/paper/build_paper.py --only ablation
    python analysis/paper/build_paper.py --only special

Important
---------
This script uses the same ROC/TPR convention as src/evaluation/plot_roc.py:
    TPR@x%FPR = the TPR at the last ROC point whose FPR <= target.
"""

