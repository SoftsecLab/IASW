def latex_main_robustness(df: pd.DataFrame) -> str:
    """
    Generate the manuscript Table 1 format exactly:

        Dataset | Method |
        Unattacked (AUROC / TPR@1% / TPR@5%) |
        8 attacked settings, each with the same three metrics.

    Values are percentages with one decimal place.
    Within each dataset/condition/metric, the best displayed value is bold
    and the second-best displayed value is underlined, matching the manuscript
    convention. Ranking is performed after rounding to one decimal because
    the paper displays one decimal place.
    """
    sub = df[df["model"] == PRIMARY_MODEL].copy()
    if sub.empty:
        return "% Main robustness table skipped: no primary-model records.\n"

    # Controlled centrally by METHOD_ORDER.
    table_methods = paper_methods()

    dataset_order = [
        ("c4", "RealNews"),
        ("dolly", "DOLLY"),
        ("wiki", "Wiki"),
    ]

    conditions = [
        ("Unattacked", "Unattacked"),
        ("typo", "Typo"),
        ("drop", "Drop"),
        ("swap", "Swap"),
        ("del_ins", "Del-Ins"),
        ("pegasus", "Pegasus"),
        ("dipper", "Dipper"),
        ("back_translation", "Back Trans"),
        ("copy_paste", "Copy Paste"),
        ("sentence_reorder", "Sent Reorder"),
    ]

    metrics = [
        ("AUC", "AUC"),
        ("TPR@1%FPR", "TPR@1%FPR"),
        ("TPR@5%FPR", "TPR@5%FPR"),
    ]

    def get_value(row, condition_key, metric_key):
        if condition_key == "Unattacked":
            return safe_float(row.get(f"Unattacked_{metric_key}", np.nan))
        return safe_float(row.get(f"{condition_key}_{metric_key}", np.nan))

    def displayed_percent(v):
        if not np.isfinite(v):
            return np.nan
        if abs(v) <= 1.5:
            v *= 100.0
        return round(float(v), 1)

    # Precompute best / second-best using the DISPLAYED one-decimal values.
    rank_map = {}
    for dataset_key, _ in dataset_order:
        ds = sub[sub["dataset"] == dataset_key]
        for condition_key, _ in conditions:
            for metric_key, _ in metrics:
                values = []
                for method in table_methods:
                    x = ds[ds["method_key"] == method]
                    if x.empty:
                        continue
                    v = displayed_percent(
                        get_value(x.iloc[0], condition_key, metric_key)
                    )
                    if np.isfinite(v):
                        values.append(v)

                distinct = sorted(set(values), reverse=True)
                best = distinct[0] if distinct else np.nan
                second = distinct[1] if len(distinct) > 1 else np.nan
                rank_map[(dataset_key, condition_key, metric_key)] = (
                    best,
                    second,
                )

    def render_cell(dataset_key, condition_key, metric_key, value):
        v = displayed_percent(value)
        if not np.isfinite(v):
            return "--"

        s = f"{v:.1f}"
        best, second = rank_map[
            (dataset_key, condition_key, metric_key)
        ]

        if np.isfinite(best) and v == best:
            return rf"\textbf{{{s}}}"
        if np.isfinite(second) and v == second:
            return rf"\underline{{{s}}}"
        return s

    tabular_spec = (
        r"l l "
        + " ".join(
            [r"c@{\,/\,}c@{\,/\,}c"] * len(conditions)
        )
    )

    header = (
        r"\textbf{Dataset} & \textbf{Method} & "
        + " & ".join(
            rf"\multicolumn{{3}}{{c}}{{\textbf{{{label}}}}}"
            for _, label in conditions
        )
        + r" \\"
    )

    lines = [
        r"\begin{table*}[htbp]",
        r"\centering",
        r"\caption{Main Robustness Evaluation against Baselines (AUROC / TPR@1\% / TPR@5\%, values in percentage)}",
        r"\label{tab:main_performance}",
        r"\resizebox{\textwidth}{!}{",
        rf"\begin{{tabular}}{{{tabular_spec}}}",
        r"\toprule",
        header,
        r"\midrule",
    ]

    for ds_idx, (dataset_key, dataset_label) in enumerate(dataset_order):
        ds = sub[sub["dataset"] == dataset_key]

        for method_idx, method in enumerate(table_methods):
            x = ds[ds["method_key"] == method]

            # Keep the paper's fixed method-row layout even if one record is
            # missing; the missing row is rendered with "--".
            row = x.iloc[0] if not x.empty else {}

            first = (
                rf"\multirow{{{len(table_methods)}}}{{*}}{{{dataset_label}}}"
                if method_idx == 0
                else ""
            )

            cells = []
            for condition_key, _ in conditions:
                for metric_key, _ in metrics:
                    cells.append(
                        render_cell(
                            dataset_key,
                            condition_key,
                            metric_key,
                            get_value(row, condition_key, metric_key),
                        )
                    )

            lines.append(
                f"{first} & {display_method(method)} & "
                + " & ".join(cells)
                + r" \\"
            )

        if ds_idx < len(dataset_order) - 1:
            lines.append(r"\midrule")

    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"}",
        r"\end{table*}",
    ]
    return "\n".join(lines) + "\n"


def latex_cross_backbone(df: pd.DataFrame) -> str:
    """
    Generate three cross-backbone robustness tables in one .tex file:
    AUROC, TPR@1%FPR, and TPR@5%FPR.
    """
    sub = df[df["dataset"] == "c4"].copy()
    if sub.empty:
        return "% Cross-backbone table skipped: no RealNews records.\n"

    table_methods = paper_methods()
    model_columns = [
        ("OPT-1.3B", "OPT-SemStamp"),
        ("Llama-3.2-3B", "Llama-3.2"),
        ("Mistral-7B", "Mistral-7B"),
        ("Qwen2.5-7B", "Qwen2.5-7B"),
        ("Llama-3.1-8B", "Llama-3.1"),
    ]

    source_rows = []
    table_blocks = []

    for metric_key, metric_label, metric_suffix in ROBUSTNESS_METRICS:
        value_col = AVG_ATTACKED_COLUMNS[metric_key]
        pivot = sub.pivot_table(
            index="method_key",
            columns="model_display",
            values=value_col,
            aggfunc="first",
        )

        rows = []
        for method in table_methods:
            vals = []
            for model_key, _ in model_columns:
                vals.append(
                    safe_float(pivot.loc[method, model_key])
                    if method in pivot.index and model_key in pivot.columns
                    else np.nan
                )
            row = {
                "metric": metric_key,
                "metric_label": metric_label,
                "method_key": method,
                "Method": display_method(method),
                **{
                    model_columns[i][1]: vals[i]
                    for i in range(len(model_columns))
                },
                "Mean": mean_or_nan(vals),
            }
            rows.append(row)
            source_rows.append(row.copy())

        metric_df = pd.DataFrame(rows)
        value_cols = [label for _, label in model_columns] + ["Mean"]
        best = {}
        for col in value_cols:
            vals = [
                round(safe_float(v) * 100.0, 1)
                for v in metric_df[col]
                if np.isfinite(safe_float(v))
            ]
            best[col] = max(vals) if vals else np.nan

        def render(v, col):
            fv = safe_float(v)
            if not np.isfinite(fv):
                return "--"
            p = round(fv * 100.0, 1)
            text = f"{p:.1f}"
            return rf"\textbf{{{text}}}" if p == best[col] else text

        lines = [
            r"\begin{table}[htbp]",
            r"\makeatletter",
            r"\long\def\@makecaption#1#2{%",
            r"  \vskip 2pt",
            r"  \noindent",
            r"  \parbox{\linewidth}{%",
            r"    \small",
            r"    \textbf{#1}\quad #2%",
            r"  }%",
            r"  \vskip 2pt",
            r"}",
            r"\makeatother",
            r"\centering",
            r"\small",
            r"\setlength{\tabcolsep}{4.5pt}",
            r"\renewcommand{\arraystretch}{1.05}",
            rf"\caption{{Cross-backbone robustness summary on RealNews measured by {metric_label}. Values are averaged over the attacked settings; unattacked results are excluded. OPT-SemStamp denotes the fine-tuned checkpoint used in the original SemStamp setting.}}",
            rf"\label{{tab:backbone_summary_{metric_suffix}}}",
            r"\resizebox{\columnwidth}{!}{",
            r"\begin{tabular}{lcccccc}",
            r"\toprule",
            r"\textbf{Method} & \textbf{OPT-SemStamp} & \textbf{Llama-3.2} & \textbf{Mistral-7B} & \textbf{Qwen2.5-7B} & \textbf{Llama-3.1} & \textbf{Mean} \\",
            r"\midrule",
        ]

        for _, row in metric_df.iterrows():
            if row["method_key"] == "dual_kgw_iasw":
                lines.append(r"\midrule")
            vals = [render(row[c], c) for c in value_cols]
            lines.append(f"{row['Method']} & " + " & ".join(vals) + r" \\")

        lines += [
            r"\bottomrule",
            r"\end{tabular}",
            r"}",
            r"\end{table}",
        ]
        table_blocks.append("\n".join(lines))

    pd.DataFrame(source_rows).to_csv(
        PAPER_CSV / "cross_backbone_source.csv",
        index=False,
        encoding="utf-8-sig",
    )
    return "\n\n".join(table_blocks) + "\n"

