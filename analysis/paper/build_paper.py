def newest_existing(paths: Iterable[Path]) -> Optional[Path]:
    existing = [p for p in paths if p.exists()]
    if not existing:
        return None
    return max(existing, key=lambda p: p.stat().st_mtime)


def build_attack_quality_table() -> Tuple[str, Optional[pd.DataFrame]]:
    root = ANALYSIS_ROOT / "quality" / "attack_quality"

